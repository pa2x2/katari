"""Writes the C source of the stand-in libmpv links in place of a library it takes from the system.

    lazy-library.py <system-libraries.txt> <soname> <output .c>

mpv and FFmpeg call the library's functions as if they linked it. The stand-in defines each of those functions as a
jump through a table. The first call into any of them opens the library with dlopen and fills the table with its
functions, so libmpv loads without the library and only the first use looks for it. When the library is missing, or
lacks one of the functions (an older version), every function of it becomes its fallback instead: it returns the
value system-libraries.txt gives, or 0, so the feature that needs the library fails the way it does when its device
or server is missing, and the rest of mpv carries on.

The jumps keep every argument register as the caller set it, so they suit any function, variadic ones too; the
fallbacks return an integer, so a function the code calls first when the library may be missing must return one.
"""

import re
import sys
from pathlib import Path

if len(sys.argv) != 4:
    sys.exit(__doc__)
spec, soname, output = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])


def read_libraries(path: Path) -> dict[str, list[tuple[str, int]]]:
    """Each library's functions with their fallback values, in the file's order."""
    libraries: dict[str, list[tuple[str, int]]] = {}
    current = None
    for number, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].rstrip()
        if not line:
            continue
        if not line[0].isspace():
            current = libraries.setdefault(line.strip(), [])
            continue
        match = re.fullmatch(r"\s+([A-Za-z_][A-Za-z0-9_]*)(?:\s*=\s*(-?[0-9]+))?", line)
        if current is None or not match:
            sys.exit(f"{path}:{number}: expected a soname or an indented function [= fallback]")
        current.append((match.group(1), int(match.group(2) or 0)))
    return libraries


libraries = read_libraries(spec)
if soname not in libraries:
    sys.exit(f"{spec} has no library {soname}")
functions = libraries[soname]
names = [name for name, _ in functions]
if len(set(names)) != len(names):
    sys.exit(f"{spec} lists a function of {soname} twice")

prefix = "katari_lazy_" + re.sub(r"[^A-Za-z0-9]", "_", soname)
count = len(functions)
values = sorted({value for _, value in functions})


def missing(value: int) -> str:
    return f"{prefix}_missing_{value}" if value >= 0 else f"{prefix}_missing_minus{-value}"


asm = [".text"]
for index, (name, _) in enumerate(functions):
    asm += [
        f".globl {name}",
        f".hidden {name}",
        f".type {name}, @function",
        f"{name}:",
        f"    jmp *{prefix}_table+{8 * index}(%rip)",
        f".size {name}, .-{name}",
        f".type {prefix}_bind_{index}, @function",
        f"{prefix}_bind_{index}:",
        f"    mov ${index}, %r11d",
        f"    jmp {prefix}_bind",
        f".size {prefix}_bind_{index}, .-{prefix}_bind_{index}",
    ]
# The first call of each function lands here with its index in r11: it saves the argument registers (rax holds the
# number of vector registers a variadic call uses), resolves, restores them and jumps on as if called directly.
saved = ["rdi", "rsi", "rdx", "rcx", "r8", "r9", "rax"]
asm += [
    f".type {prefix}_bind, @function",
    f"{prefix}_bind:",
    "    push %rbp",
    "    mov %rsp, %rbp",
    "    sub $192, %rsp",
]
asm += [f"    mov %{register}, {8 * slot}(%rsp)" for slot, register in enumerate(saved)]
asm += [f"    movaps %xmm{slot}, {64 + 16 * slot}(%rsp)" for slot in range(8)]
asm += ["    mov %r11, %rdi", f"    call {prefix}_resolve", "    mov %rax, %r11"]
asm += [f"    mov {8 * slot}(%rsp), %{register}" for slot, register in enumerate(saved)]
asm += [f"    movaps {64 + 16 * slot}(%rsp), %xmm{slot}" for slot in range(8)]
asm += ["    leave", "    jmp *%r11", f".size {prefix}_bind, .-{prefix}_bind"]
for value in values:
    label = missing(value)
    asm += [f".type {label}, @function", f"{label}:", f"    mov ${value}, %rax", "    ret", f".size {label}, .-{label}"]


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    f"/* Generated by tools/libmpv/lazy-library.py from system-libraries.txt: {soname}, opened on first use. */",
    "#include <dlfcn.h>",
    "#include <pthread.h>",
    "#include <stddef.h>",
    "",
    "#define HIDDEN __attribute__((visibility(\"hidden\")))",
    "",
]
lines += [f"HIDDEN void {prefix}_bind_{index}(void);" for index in range(count)]
lines += [f"HIDDEN void {missing(value)}(void);" for value in values]
lines += [
    "HIDDEN void *" + prefix + "_resolve(size_t index);",
    "",
    f"static const char *const names[{count}] = {{",
    *[f"    {c_string(name)}," for name in names],
    "};",
    "",
    f"static void (*const fallbacks[{count}])(void) = {{",
    *[f"    {missing(value)}," for _, value in functions],
    "};",
    "",
    "/* What each function jumps to: its first-call binder, then the library's function or its fallback. */",
    f"HIDDEN void *{prefix}_table[{count}] = {{",
    *[f"    (void *) {prefix}_bind_{index}," for index in range(count)],
    "};",
    "",
    "static pthread_once_t once = PTHREAD_ONCE_INIT;",
    "",
    "static void load(void)",
    "{",
    f"    void *found[{count}];",
    "    size_t i = 0;",
    f"    void *handle = dlopen({c_string(soname)}, RTLD_NOW | RTLD_LOCAL);",
    "    if (handle) {",
    f"        for (; i < {count}; i++) {{",
    "            if (!(found[i] = dlsym(handle, names[i])))",
    "                break;",
    "        }",
    f"        if (i < {count})",
    "            dlclose(handle);",
    "    }",
    f"    for (size_t j = 0; j < {count}; j++) {{",
    f"        void *target = handle && i == {count} ? found[j] : (void *) fallbacks[j];",
    f"        __atomic_store_n(&{prefix}_table[j], target, __ATOMIC_RELEASE);",
    "    }",
    "}",
    "",
    f"void *{prefix}_resolve(size_t index)",
    "{",
    "    pthread_once(&once, load);",
    f"    return __atomic_load_n(&{prefix}_table[index], __ATOMIC_ACQUIRE);",
    "}",
    "",
    "__asm__(",
    *[f'    "{line}\\n"' for line in asm],
    ");",
    "",
]
output.write_text("\n".join(lines))
