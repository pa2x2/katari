FIXED_TIME = (2000, 1, 1, 0, 0, 0)

if sorted(name for name, _, _ in components) != sorted(COMPONENTS):
    sys.exit(f"pack-jar.py describes {sorted(COMPONENTS)}, not {sorted(name for name, _, _ in components)}")


def licence_text(source: Path, files: str) -> str:
    texts = []
    for file in files.split():
        if file.endswith("#"):
            comments = re.findall(r"/\*.*?\*/", (source / file[:-1]).read_text(), re.S)
            comment = next(comment for comment in comments if "Permission is hereby granted" in comment)
            text = "\n".join(re.sub(r"^\s*/?\*+/?\s?", "", line) for line in comment.splitlines()).strip() + "\n"
        else:
            text = (source / file).read_text()
        if text not in texts:
            texts.append(text)
    return "\n".join(texts)


def add(archive: zipfile.ZipFile, name: str, data: bytes, mode: int = 0o644):
    info = zipfile.ZipInfo(name, FIXED_TIME)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = mode << 16
    archive.writestr(info, data)


for directory in ("libraries", "licenses"):
    (licences / directory).mkdir(parents=True, exist_ok=True)
    for stale in (licences / directory).glob(f"{SLUG_PREFIX}*.json"):
        stale.unlink()
with zipfile.ZipFile(jar, "w") as archive:
    add(archive, "META-INF/MANIFEST.MF", b"Manifest-Version: 1.0\r\nCreated-By: tools/libmpv\r\n\r\n")
    add(archive, "linux-x86-64/libmpv.so", library.read_bytes(), 0o755)
    for name, version, source in components:
        licence_files, licence_name, website, description = COMPONENTS[name]
        text = licence_text(Path(source), licence_files)
        add(archive, f"META-INF/licences/{name}.txt", text.encode())
        slug = SLUG_PREFIX + name.lower().replace("+", "x").replace("_", "-")
        (licences / "licenses" / f"{slug}.json").write_text(
            json.dumps({"hash": slug, "name": licence_name, "content": text}, ensure_ascii=False, indent=2) + "\n",
        )
        library_entry = {
            "uniqueId": JAR_ID if name == "mpv" else f"app.katari.libmpv:{slug.removeprefix(SLUG_PREFIX)}",
            "artifactVersion": version,
            "name": name,
            "description": description,
            "website": website,
            "licenses": [slug],
        }
        (licences / "libraries" / f"{slug}.json").write_text(
            json.dumps(library_entry, ensure_ascii=False, indent=2) + "\n",
        )
