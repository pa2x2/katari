"""Packs a built libmpv.so into the jar the desktop app loads it from, and writes the licences screen's entries.

    pack-jar.py <libmpv.so> <jar> <licences directory> <name>=<version>=<source directory>...

The library sits at JNA's resource path for x86_64 Linux. The jar carries the licence of each component built into the
library, as their licences ask of a binary, and the licences directory gets one AboutLibraries library and licence
entry per component, in the layout the desktop app's AboutLibraries configuration reads, beside the entries other
tools write there. The mpv entry takes the jar's own coordinates, so it stands in for the entry AboutLibraries finds
for the jar, which has no POM to describe it. Entry times are fixed, so the same library always packs into the same
jar.
"""

import json
import re
import sys
import zipfile
from pathlib import Path

if len(sys.argv) < 5:
    sys.exit(__doc__)
library, jar, licences = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
components = [argument.split("=", 2) for argument in sys.argv[4:]]

JAR_ID = "app.katari.libmpv:libmpv-linux-x86-64"
SLUG_PREFIX = "libmpv-desktop-"
BUILT_IN = "Built into the desktop app's libmpv."
