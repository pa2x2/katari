package app.katari.gradle.telemetry

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `PostHogProjectToken`, the token that lets the app's events into Katari's PostHog project. Only Katari's
 * release workflow passes the token, so every other build, a release-variant one made on a developer's machine or in
 * CI among them, carries none and sends nothing.
 */
@CacheableTask
abstract class GeneratePostHogProjectTokenTask : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    @get:Optional
    abstract val token: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val token = token.orNull
        if (token != null && !TOKEN_FORMAT.matches(token)) {
            throw GradleException("The PostHog project token must look like phc_<letters and digits>")
        }
        val value = token?.let { "\"$it\"" } ?: "null"
        val code = """
            |// Generated by ${GeneratePostHogProjectTokenTask::class.simpleName}.
            |package ${packageName.get()}
            |
            |internal object PostHogProjectToken {
            |    val value: String? = $value
            |}
            |
        """.trimMargin()
        val directory = outputDir.get().asFile
        directory.deleteRecursively()
        val file = directory.resolve(packageName.get().replace('.', '/')).resolve("PostHogProjectToken.kt")
        file.parentFile.mkdirs()
        file.writeText(code)
    }

    private companion object {
        val TOKEN_FORMAT = Regex("phc_[A-Za-z0-9]+")
    }
}
