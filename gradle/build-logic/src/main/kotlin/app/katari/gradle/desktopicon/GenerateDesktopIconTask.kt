package app.katari.gradle.desktopicon

import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes the desktop app's icon as an SVG from the layers of the Android app's adaptive launcher icon, so both apps
 * show one icon, and a development build the development one. A desktop has no launcher to mask the layers, so they
 * are drawn whole in the rounded square of the app's logo, as the website shows it (`website/src/site/katari.svg`).
 */
@CacheableTask
abstract class GenerateDesktopIconTask : DefaultTask() {

    /** A vector drawable. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val background: RegularFileProperty

    /** A vector drawable of the same size as [background]. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val foreground: RegularFileProperty

    @get:OutputFile
    abstract val icon: RegularFileProperty

    @TaskAction
    fun generate() {
        val background = readVectorDrawable(background.get().asFile)
        val foreground = readVectorDrawable(foreground.get().asFile)
        check(background.width == foreground.width && background.height == foreground.height) {
            "The icon's layers differ in size"
        }
        val width = background.viewportWidth
        val height = background.viewportHeight
        val corner = svgNumber(minOf(width, height) * LOGO_CORNER)
        val svg = buildString {
            appendLine("<!-- Generated by ${GenerateDesktopIconTask::class.simpleName} -->")
            appendLine(
                "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 ${svgNumber(width)} ${svgNumber(height)}\">",
            )
            appendLine("<defs><clipPath id=\"shape\">")
            appendLine("<rect width=\"${svgNumber(width)}\" height=\"${svgNumber(height)}\" rx=\"$corner\"/>")
            appendLine("</clipPath></defs>")
            appendLine("<g clip-path=\"url(#shape)\">")
            appendLayer(background, width, height)
            appendLayer(foreground, width, height)
            appendLine("</g>")
            appendLine("</svg>")
        }
        icon.get().asFile.apply { parentFile.mkdirs() }.writeText(svg)
    }

    // Each layer is drawn in its own viewport, stretched over the icon's
    private fun StringBuilder.appendLayer(layer: VectorDrawableSvg, width: Double, height: Double) {
        val scaleX = width / layer.viewportWidth
        val scaleY = height / layer.viewportHeight
        if (scaleX == 1.0 && scaleY == 1.0) {
            appendLine("<g>${layer.content}</g>")
        } else {
            appendLine("<g transform=\"scale(${svgNumber(scaleX)} ${svgNumber(scaleY)})\">${layer.content}</g>")
        }
    }
}

/** The corner radius of the rounded square the app's logo is drawn in, as a share of its side: 30 of 128. */
internal const val LOGO_CORNER = 30.0 / 128.0
