package app.katari.gradle.tasks

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/** Writes `AppLocaleTags`, the languages the app can be shown in, for its language list on every platform. */
@CacheableTask
abstract class GenerateAppLocaleTagsTask : DefaultTask() {

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val localeFiles: ConfigurableFileCollection

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val tags = localeResourceTags(localeFiles).joinToString("\n") { "|    \"$it\"," }
        val code = """
            |// Generated by ${GenerateAppLocaleTagsTask::class.simpleName}.
            |package ${packageName.get()}
            |
            |/** The languages the app has strings in, as the language tags Android's locales_config.xml lists. */
            |val AppLocaleTags: List<String> = listOf(
            $tags
            |)
            |
        """.trimMargin()
        val directory = outputDir.get().asFile
        directory.deleteRecursively()
        directory.resolve(packageName.get().replace('.', '/')).resolve("AppLocaleTags.kt").apply {
            parentFile.mkdirs()
            writeText(code)
        }
    }
}
