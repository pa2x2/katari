package app.katari.gradle.tasks

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Writes `DesktopBuildInfo`, the desktop app's counterpart of the Android app's generated `BuildConfig`: the desktop
 * app's own version, the commit the build was made from, how many commits lead up to it, when it was committed, and
 * whether it is the release or a development build, and the Chromium its web view runs on. Also writes `eu.kanade.tachiyomi.BuildConfig` with the Android
 * app's version name and code, which extensions read reflectively through `AppInfo`, as they do on Android: extensions
 * are written against the Android app's versions, whatever the desktop app's own is.
 */
@CacheableTask
abstract class GenerateDesktopBuildInfoTask : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val androidVersionName: Property<String>

    @get:Input
    abstract val androidVersionCode: Property<Int>

    @get:Input
    abstract val commitSha: Property<String>

    @get:Input
    abstract val commitCount: Property<String>

    /** An ISO 8601 instant. */
    @get:Input
    abstract val buildTime: Property<String>

    @get:Input
    abstract val release: Property<Boolean>

    /** The Chromium the app's web view runs on, as `gradle/katari.versions.toml` pins it. */
    @get:Input
    abstract val chromiumVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val code = """
            |// Generated by ${GenerateDesktopBuildInfoTask::class.simpleName}.
            |package ${packageName.get()}
            |
            |internal object DesktopBuildInfo {
            |    const val VERSION_NAME: String = ${versionName.get().toKotlinStringLiteral()}
            |    const val COMMIT_SHA: String = ${commitSha.get().toKotlinStringLiteral()}
            |    const val COMMIT_COUNT: String = ${commitCount.get().toKotlinStringLiteral()}
            |    const val BUILD_TIME: String = ${buildTime.get().toKotlinStringLiteral()}
            |    const val IS_RELEASE: Boolean = ${release.get()}
            |    const val CHROMIUM_VERSION: String = ${chromiumVersion.get().toKotlinStringLiteral()}
            |}
            |
        """.trimMargin()
        val extensionBuildConfig = """
            |// Generated by ${GenerateDesktopBuildInfoTask::class.simpleName}.
            |package $EXTENSION_BUILD_CONFIG_PACKAGE
            |
            |object BuildConfig {
            |    const val VERSION_CODE: Int = ${androidVersionCode.get()}
            |    const val VERSION_NAME: String = ${androidVersionName.get().toKotlinStringLiteral()}
            |}
            |
        """.trimMargin()
        val directory = outputDir.get().asFile
        directory.deleteRecursively()
        directory.writeSource(packageName.get(), "DesktopBuildInfo", code)
        directory.writeSource(EXTENSION_BUILD_CONFIG_PACKAGE, "BuildConfig", extensionBuildConfig)
    }

    private fun File.writeSource(packageName: String, name: String, code: String) {
        val file = resolve(packageName.replace('.', '/')).resolve("$name.kt")
        file.parentFile.mkdirs()
        file.writeText(code)
    }

    private companion object {
        const val EXTENSION_BUILD_CONFIG_PACKAGE = "eu.kanade.tachiyomi"
    }
}

private fun String.toKotlinStringLiteral(): String {
    val escaped = replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
    return "\"$escaped\""
}
