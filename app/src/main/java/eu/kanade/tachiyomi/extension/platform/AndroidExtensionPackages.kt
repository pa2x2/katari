package eu.kanade.tachiyomi.extension.platform

import android.content.Context
import android.content.pm.ApplicationInfo
import android.content.pm.PackageManager
import android.os.Build
import dev.zacsweers.metro.Inject
import java.io.File

/**
 * The packages [PackageManager] has installed, and the app's private copies, each a read-only file named
 * `<package>.ext` in [ExtensionFiles.privateApkDir].
 */
@Inject
class AndroidExtensionPackages(
    private val context: Context,
    private val files: ExtensionFiles,
) : ExtensionPackages {

    private val pkgManager: PackageManager
        get() = context.packageManager

    override fun shared(): List<ExtensionPackage> {
        val installedPkgs = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            pkgManager.getInstalledPackages(PackageManager.PackageInfoFlags.of(PACKAGE_FLAGS.toLong()))
        } else {
            pkgManager.getInstalledPackages(PACKAGE_FLAGS)
        }
        return installedPkgs.map { AndroidExtensionPackage(it, isShared = true, pkgManager) }
    }

    override fun shared(packageName: String): ExtensionPackage? {
        return try {
            AndroidExtensionPackage(pkgManager.getPackageInfo(packageName, PACKAGE_FLAGS), isShared = true, pkgManager)
        } catch (_: PackageManager.NameNotFoundException) {
            null
        }
    }

    override fun private(): Map<File, ExtensionPackage?> {
        return files.privateApkDir
            .listFiles()
            .orEmpty()
            .filter { it.isFile && it.extension == PRIVATE_EXTENSION_EXTENSION }
            .associateWith {
                // Just in case, since Android 14+ requires them to be read-only
                if (it.canWrite()) {
                    it.setReadOnly()
                }
                readPrivateArchive(it)
            }
    }

    override fun private(packageName: String): ExtensionPackage? {
        val privateExtensionFile = privateApk(files, packageName)
        return if (privateExtensionFile.isFile) readPrivateArchive(privateExtensionFile) else null
    }

    override fun downloaded(file: File): ExtensionPackage? {
        return pkgManager.getPackageArchiveInfo(file.absolutePath, PACKAGE_FLAGS)
            ?.let { AndroidExtensionPackage(it, isShared = false, pkgManager) }
    }

    /** Null when Android can't parse the file, such as a truncated or damaged one. */
    private fun readPrivateArchive(file: File): ExtensionPackage? {
        val path = file.absolutePath
        return pkgManager.getPackageArchiveInfo(path, PACKAGE_FLAGS)
            ?.also { it.applicationInfo?.fixBasePaths(path) }
            ?.let { AndroidExtensionPackage(it, isShared = false, pkgManager) }
    }

    /**
     * On Android 13+ the ApplicationInfo generated by getPackageArchiveInfo doesn't
     * have sourceDir which breaks assets loading (used for getting icon here).
     */
    private fun ApplicationInfo.fixBasePaths(apkPath: String) {
        if (sourceDir == null) {
            sourceDir = apkPath
        }
        if (publicSourceDir == null) {
            publicSourceDir = apkPath
        }
    }

    companion object {
        @Suppress("DEPRECATION")
        private val PACKAGE_FLAGS = PackageManager.GET_CONFIGURATIONS or
            PackageManager.GET_META_DATA or
            PackageManager.GET_SIGNATURES or
            (if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) PackageManager.GET_SIGNING_CERTIFICATES else 0)

        private const val PRIVATE_EXTENSION_EXTENSION = "ext"

        /** Where the private copy of [packageName] is kept. */
        fun privateApk(files: ExtensionFiles, packageName: String): File =
            File(files.privateApkDir, "$packageName.$PRIVATE_EXTENSION_EXTENSION")
    }
}
