package mihon.presentation.kit.theme

import androidx.compose.ui.graphics.Color

/**
 * Colours behind manga pages, picked by the reader's background setting rather than the theme, so a page looks the same
 * whichever theme the app uses.
 */
object PageBackgroundColors {
    val white: Color = Color.White
    val black: Color = Color.Black
    val gray: Color = Color(0xFF202125)
}
